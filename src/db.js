const fs = require('node:fs');
const path = require('node:path');
const { DatabaseSync } = require('node:sqlite');

const SCHEMA = `
CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE COLLATE NOCASE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin','sales')),
  active INTEGER NOT NULL DEFAULT 1,
  is_demo INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL,
  deactivated_at TEXT
);
CREATE TABLE IF NOT EXISTS sessions (
  token TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS pipelines (
  id INTEGER PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT,
  position INTEGER NOT NULL DEFAULT 0,
  archived_at TEXT,
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS stages (
  id INTEGER PRIMARY KEY,
  pipeline_id INTEGER NOT NULL REFERENCES pipelines(id),
  name TEXT NOT NULL,
  outcome TEXT NOT NULL CHECK (outcome IN ('open','won','lost')),
  position INTEGER NOT NULL DEFAULT 0,
  archived_at TEXT
);
CREATE TABLE IF NOT EXISTS contacts (
  id INTEGER PRIMARY KEY,
  name TEXT,
  phone TEXT,
  phone_norm TEXT,
  email TEXT,
  email_norm TEXT,
  is_demo INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_contacts_phone ON contacts(phone_norm);
CREATE INDEX IF NOT EXISTS idx_contacts_email ON contacts(email_norm);
CREATE TABLE IF NOT EXISTS leads (
  id INTEGER PRIMARY KEY,
  contact_id INTEGER NOT NULL REFERENCES contacts(id),
  pipeline_id INTEGER NOT NULL REFERENCES pipelines(id),
  stage_id INTEGER NOT NULL REFERENCES stages(id),
  owner_id INTEGER REFERENCES users(id),
  source TEXT NOT NULL DEFAULT 'other',
  vehicle TEXT,
  enquiry TEXT,
  reg_number TEXT,
  reg_norm TEXT,
  listing_id TEXT,
  listing_url TEXT,
  outcome TEXT NOT NULL DEFAULT 'open' CHECK (outcome IN ('open','won','lost')),
  won_at TEXT,
  lost_at TEXT,
  lost_reason TEXT,
  lost_note TEXT,
  next_action TEXT,
  next_action_due TEXT,
  is_demo INTEGER NOT NULL DEFAULT 0,
  created_by INTEGER REFERENCES users(id),
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_leads_pipeline ON leads(pipeline_id, stage_id);
CREATE INDEX IF NOT EXISTS idx_leads_owner ON leads(owner_id, outcome);
CREATE INDEX IF NOT EXISTS idx_leads_contact ON leads(contact_id);
-- One timeline per lead. type: created | note | call | email | followup_done | stage_change | owner_change | edit
-- origin: manual (entered by a user) | sample (synthetic demo conversation) | system (generated by the CRM)
CREATE TABLE IF NOT EXISTS activities (
  id INTEGER PRIMARY KEY,
  lead_id INTEGER NOT NULL REFERENCES leads(id),
  user_id INTEGER REFERENCES users(id),
  type TEXT NOT NULL,
  origin TEXT NOT NULL DEFAULT 'manual',
  direction TEXT CHECK (direction IN ('in','out') OR direction IS NULL),
  occurred_at TEXT NOT NULL,
  call_outcome TEXT,
  duration_sec INTEGER,
  subject TEXT,
  body TEXT,
  due_at TEXT,
  from_stage_id INTEGER,
  to_stage_id INTEGER,
  from_user_id INTEGER,
  to_user_id INTEGER,
  lost_reason TEXT,
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_activities_lead ON activities(lead_id, occurred_at);
CREATE INDEX IF NOT EXISTS idx_activities_type ON activities(type, occurred_at);
CREATE TABLE IF NOT EXISTS app_meta (key TEXT PRIMARY KEY, value TEXT);
`;

function openDb(file) {
  if (file !== ':memory:') fs.mkdirSync(path.dirname(file), { recursive: true });
  const db = new DatabaseSync(file);
  db.exec('PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON; PRAGMA busy_timeout = 5000;');
  db.exec(SCHEMA);
  return db;
}

// Serialised write transaction. BEGIN IMMEDIATE takes the write lock up front, so concurrent
// writers (even from other processes) queue instead of interleaving.
function tx(db, fn) {
  db.exec('BEGIN IMMEDIATE');
  try {
    const r = fn();
    db.exec('COMMIT');
    return r;
  } catch (e) {
    try { db.exec('ROLLBACK'); } catch (_) { /* ignore */ }
    throw e;
  }
}

function wipe(db) {
  db.exec(`DELETE FROM activities; DELETE FROM leads; DELETE FROM contacts; DELETE FROM sessions;
    DELETE FROM stages; DELETE FROM pipelines; DELETE FROM users; DELETE FROM app_meta;`);
}

module.exports = { openDb, tx, wipe };
